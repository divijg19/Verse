-- Migration: one editable draft per submission branch.
--
-- v0.5.5 kept a single continuous body per private link. The author could compare an alternative by
-- sending it as a separate submission branch, but the guest had one textarea and no way to return to
-- an earlier version. This migration gives each branch its own draft: the primary body the guest was
-- originally given, and one body for every alternative they chose to keep.
--
-- Existing rows belong to the primary branch. The primary key becomes (link_id, branch), so every
-- read and write is still scoped to the signed session's link and a guest cannot name another
-- link's branch. The branch CHECK matches work_proposals.branch; an alternative id is a UUID with
-- the "alt:" prefix generated by the service.
--
-- No role grants are needed: verse_runtime already holds SELECT, INSERT and UPDATE on this table
-- from 009, and those table-level privileges cover the new column and the new key.

ALTER TABLE guest_drafts
    ADD COLUMN IF NOT EXISTS branch TEXT NOT NULL DEFAULT 'primary'
        CHECK (branch = 'primary' OR branch LIKE 'alt:________-____-____-____-____________');

-- Replace the single-link primary key with the composite one. IF EXISTS keeps a partially applied
-- migration recoverable; the columns are already NOT NULL.
ALTER TABLE guest_drafts DROP CONSTRAINT IF EXISTS guest_drafts_pkey;
ALTER TABLE guest_drafts ADD PRIMARY KEY (link_id, branch);
