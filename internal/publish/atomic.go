package publish

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// WriteDir writes the rendered build to out, replacing any previous build only after every file has
// been written successfully.
//
// The sequence is: build in a sibling temporary directory, move the old directory aside, move the new
// one into place, then delete the old one. A failure before the second rename leaves the previous
// output untouched, which is the property that matters when a build is interrupted halfway through.
func WriteDir(out string, files map[string][]byte) (err error) {
	if strings.TrimSpace(out) == "" {
		return errors.New("output directory is empty")
	}

	target := filepath.Clean(out)
	if target == "." || target == string(filepath.Separator) {
		return fmt.Errorf("refusing to replace %q; choose a dedicated output directory", out)
	}

	parent := filepath.Dir(target)
	// #nosec G301 -- this tree is a static site. The operator, a deployment command, and possibly a
	// local web server run as different users, so world traversal is the intended mode.
	if mkdirErr := os.MkdirAll(parent, 0o755); mkdirErr != nil {
		return fmt.Errorf("create the parent of %s: %w", target, mkdirErr)
	}

	tmp, mkdirErr := os.MkdirTemp(parent, ".verse-dist-")
	if mkdirErr != nil {
		return fmt.Errorf("create a temporary build directory: %w", mkdirErr)
	}
	// A successful rename empties this variable, so the deferred cleanup only removes a build that
	// never reached the output path.
	defer func() {
		if tmp != "" {
			if cleanupErr := os.RemoveAll(tmp); cleanupErr != nil && err == nil {
				err = fmt.Errorf("remove the temporary build directory %s: %w", tmp, cleanupErr)
			}
		}
	}()

	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		relative, pathErr := safeRelativePath(name)
		if pathErr != nil {
			return pathErr
		}

		destination := filepath.Join(tmp, relative)
		// #nosec G301 -- see the note on the output root above.
		if dirErr := os.MkdirAll(filepath.Dir(destination), 0o755); dirErr != nil {
			return fmt.Errorf("create a directory for %s: %w", name, dirErr)
		}
		// #nosec G306 -- these files are meant to be read by a static host and by the operator.
		if writeErr := os.WriteFile(destination, files[name], 0o644); writeErr != nil {
			return fmt.Errorf("write %s: %w", name, writeErr)
		}
	}

	backup, moveErr := moveAside(target)
	if moveErr != nil {
		return moveErr
	}

	if renameErr := os.Rename(tmp, target); renameErr != nil {
		if backup != "" {
			if restoreErr := os.Rename(backup, target); restoreErr != nil {
				return fmt.Errorf("replace %s: %w (and restoring %s failed: %w)",
					target, renameErr, backup, restoreErr)
			}
		}
		return fmt.Errorf("replace %s: %w", target, renameErr)
	}
	tmp = ""

	if backup != "" {
		if removeErr := os.RemoveAll(backup); removeErr != nil {
			return fmt.Errorf("remove the previous build at %s: %w", backup, removeErr)
		}
	}

	return nil
}

// moveAside renames an existing output directory to a unique sibling, returning its path. A missing
// output directory is not an error: the first build has nothing to replace.
func moveAside(target string) (string, error) {
	info, err := os.Stat(target)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return "", nil
		}
		return "", fmt.Errorf("inspect %s: %w", target, err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("refusing to replace %s: it exists and is not a directory", target)
	}

	placeholder, err := os.MkdirTemp(filepath.Dir(target), ".verse-dist-old-")
	if err != nil {
		return "", fmt.Errorf("reserve a backup path for %s: %w", target, err)
	}
	if err := os.Remove(placeholder); err != nil {
		return "", fmt.Errorf("prepare the backup path %s: %w", placeholder, err)
	}
	if err := os.Rename(target, placeholder); err != nil {
		return "", fmt.Errorf("move the previous build aside: %w", err)
	}
	return placeholder, nil
}

// safeRelativePath keeps a rendered path inside the output directory. The keys are generated by this
// package, not by a user, but the check is the difference between a misplaced rename and a build that
// writes over its own parent.
func safeRelativePath(name string) (string, error) {
	if name == "" {
		return "", errors.New("output path is empty")
	}
	if filepath.IsAbs(name) {
		return "", fmt.Errorf("output path %q is absolute", name)
	}

	clean := filepath.Clean(name)
	if clean == "." || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("output path %q escapes the output directory", name)
	}
	return clean, nil
}
